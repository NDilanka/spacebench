"""Convert the Hershey font file futural.jhf (Roman Simplex, kept beside this script) into the stroke data
in js/sb-hershey.js: one line per stroke, as a pen plotter draws it. The acknowledgement in
fonts/Hershey-ACKNOWLEDGEMENT.txt is written into the output, because the licence asks that it travel with the data."""
import json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
BRAND = HERE.parents[1]
name = 'futural'
raw = (HERE / (name + '.jhf')).read_text().split('\n')
glyphs, i = [], 0
while i < len(raw):
    l = raw[i]; i += 1
    if len(l) < 8: continue
    n = int(l[5:8]); body = l[8:]
    while len(body) < n * 2 and i < len(raw): body += raw[i]; i += 1
    left, right = ord(body[0]) - 82, ord(body[1]) - 82
    strokes, cur = [], []
    for k in range(1, n):
        a, b = body[2 * k], body[2 * k + 1]
        if a == ' ' and b == 'R':
            if cur: strokes.append(cur); cur = []
        else: cur.append([ord(a) - 82 - left, ord(b) - 82])
    if cur: strokes.append(cur)
    glyphs.append({'w': right - left, 's': strokes})
assert len(glyphs) >= 95, len(glyphs)
out = {chr(32 + k): g for k, g in enumerate(glyphs[:95])}
ack = (BRAND / 'fonts' / 'Hershey-ACKNOWLEDGEMENT.txt').read_text(encoding='utf-8').rstrip('\n')
head = '/* Plotter alphabet: Hershey Roman Simplex, as single strokes. Generated by build/gen/hershey.py.\n' + \
    '\n'.join(('   ' + l).rstrip() if l else '   ' for l in ack.split('\n')) + '\n*/\n'
(BRAND / 'js' / 'sb-hershey.js').write_text(head + 'window.SB_HERSHEY = ' + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf-8', newline='\n')
ys = [p[1] for g in out.values() for s in g['s'] for p in s]
print(name, len(out), 'glyphs; y range', min(ys), max(ys), '; cap y range', min(p[1] for s in out['H']['s'] for p in s), max(p[1] for s in out['H']['s'] for p in s))
