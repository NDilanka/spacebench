"""Build what the pages in brand/tools/ need.

tools/plume.js   the plume field as data URIs. A page opened from disk cannot read a canvas it has drawn
                 a file image into, so the post-image tool takes its grounds from here instead of textures/.
Run after build_texture.py.
Needs: pip install pillow
"""
import base64, io, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
BRAND = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(BRAND, "tools")
os.makedirs(OUT, exist_ok=True)

# key: (source, longest side in px). The sheet crop is the ground; the square crop shows through the plate.
PLUME = {
    "sheetFilm": ("plume-sheet-film.jpg", 2000), "sheetInk": ("plume-sheet-ink.jpg", 2000),
    "squareFilm": ("plume-square-film.jpg", 900), "squareInk": ("plume-square-ink.jpg", 900),
}
parts, total = [], 0
for key, (file, side) in PLUME.items():
    im = Image.open(os.path.join(BRAND, "textures", file)).convert("RGB")
    k = side / max(im.size)
    im = im.resize((round(im.size[0] * k), round(im.size[1] * k)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "JPEG", quality=86, optimize=True)
    total += buf.tell()
    parts.append(f'  {key}: "data:image/jpeg;base64,{base64.b64encode(buf.getvalue()).decode()}"')
    print(key, file, im.size, buf.tell() // 1024, "KB")
js = "/* Generated by brand/build/build_tools.py from textures/. Do not edit by hand. */\nwindow.SBPlume = {\n" + ",\n".join(parts) + "\n};\n"
with open(os.path.join(OUT, "plume.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write(js)
print("tools/plume.js", len(js) // 1024, "KB")
